export const dictionaries: Record<Locale, Record<I18nKey, string>> = { fr, en };

/** Remplace les jetons {name} d'une chaîne par les valeurs fournies. */
export function interpolate(value: string, vars?: Record<string, string | number>): string {
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/**
 * Traduction hors React : les modules purs (libellés de navigation, registres)
 * traduisent avec une locale explicite, qui vaut FR par défaut — c'est aussi le
 * repli quand une clé manque dans la langue demandée.
 */
export function translate(
  locale: Locale,
  key: I18nKey,
  vars?: Record<string, string | number>,
): string {
  return interpolate(dictionaries[locale]?.[key] ?? fr[key] ?? key, vars);
}
